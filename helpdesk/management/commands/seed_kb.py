class Command(BaseCommand):
    help = "Create 8 demo knowledge base entries if not present"

    def handle(self, *args, **options):
        count = 0
        for slug, title, content, keywords in ARTICLES:
            _, created = KnowledgeArticle.objects.get_or_create(slug=slug, defaults={
                "title": title, "content": content, "keywords": keywords})
            count += int(created)
        self.stdout.write(self.style.SUCCESS(f"Added {count} articles"))
